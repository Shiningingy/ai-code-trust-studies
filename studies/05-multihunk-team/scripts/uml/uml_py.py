"""Static UML class graph of a Python source tree (PlantUML text), from the standard-library `ast` only.

Deterministic: files and members are sorted, nothing is imported or executed, no model is involved.
Contents per class: fields (class-level assignments and `self.x = ...` in methods), method signatures
(with property / classmethod / staticmethod stereotypes), bases (--|>), associations (-->, a field
assigned an instance of a repo class) and dependencies (..>, any other use of a repo class by name).
Each module with top-level functions also gets a `<<module>>` box listing them, with its dependencies.

Usage: python -I uml_py.py <source root> <package dir relative to root>[,<more>] <out.puml>
       (package dirs are read non-recursively; tests/ directories are never read)
Library use: build(root, dirs) -> (puml text, stats dict)
"""
import ast
import json
import sys
from pathlib import Path


def mod_name(root, path):
    rel = path.relative_to(root).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return ".".join(parts)


def py_files(root, dirs):
    out = []
    for d in dirs:
        for p in sorted((root / d).glob("*.py")):
            if "tests" not in p.relative_to(root).parts:
                out.append(p)
    return out


def arg_str(a):
    def one(x, default=None):
        s = x.arg
        if x.annotation is not None:
            s += ": " + ast.unparse(x.annotation)
        if default is not None:
            s += "=" + ast.unparse(default)[:20]
        return s
    pos = a.posonlyargs + a.args
    defaults = [None] * (len(pos) - len(a.defaults)) + list(a.defaults)
    items = [one(x, d) for x, d in zip(pos, defaults)]
    if a.vararg:
        items.append("*" + a.vararg.arg)
    elif a.kwonlyargs:
        items.append("*")
    items += [one(x, d) for x, d in zip(a.kwonlyargs, a.kw_defaults)]
    if a.kwarg:
        items.append("**" + a.kwarg.arg)
    return ", ".join(items)


def stereo(fn):
    tags = []
    for d in fn.decorator_list:
        n = ast.unparse(d)
        if n in ("property", "classmethod", "staticmethod", "abstractmethod") or n.endswith(".setter"):
            tags.append(n)
    return ("{static} " if "staticmethod" in tags else "") + (f"<<{','.join(tags)}>> " if tags else "")


def vis(name):
    return "-" if name.startswith("__") and not name.endswith("__") else "#" if name.startswith("_") else "+"


def build(root, dirs):
    root = Path(root)
    files = py_files(root, dirs)
    trees = {}
    for p in files:
        trees[mod_name(root, p)] = ast.parse(p.read_text(encoding="utf-8", errors="replace"), str(p))
    classes = {}  # qualified name -> ClassDef
    for m, t in trees.items():
        for n in t.body:
            if isinstance(n, ast.ClassDef):
                classes[f"{m}.{n.name}"] = (m, n)

    def imports(m, t, is_pkg):
        """local name -> qualified name (module or class) for the repo's own names."""
        names = {}
        pkg = m if is_pkg else m.rsplit(".", 1)[0]
        for n in t.body:
            if isinstance(n, ast.ImportFrom):
                base = n.module or ""
                if n.level:
                    up = pkg.split(".")
                    up = up[:len(up) - (n.level - 1)]
                    base = ".".join(up + ([base] if base else []))
                for a in n.names:
                    if a.name == "*":
                        for q, (cm, cn) in classes.items():
                            if cm == base and not cn.name.startswith("_"):
                                names[cn.name] = q
                    else:
                        names[a.asname or a.name] = f"{base}.{a.name}"
            elif isinstance(n, ast.Import):
                for a in n.names:
                    names[a.asname or a.name.split(".")[0]] = a.name if a.asname else a.name.split(".")[0]
        for q, (cm, cn) in classes.items():
            if cm == m:
                names[cn.name] = q
        return names

    def resolve(node, names):
        if isinstance(node, ast.Name):
            q = names.get(node.id)
            return q if q in classes else None
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            base = names.get(node.value.id)
            if base:
                q = f"{base}.{node.attr}"
                return q if q in classes else None
        return None

    def uses(body_nodes, names, own):
        found = set()
        for b in body_nodes:
            for x in ast.walk(b):
                if isinstance(x, (ast.Name, ast.Attribute)):
                    q = resolve(x, names)
                    if q and q != own:
                        found.add(q)
        return found

    lines, edges = ["@startuml", "' generated by uml_py.py from the buggy checkout; static AST only"], set()
    n_classes = n_members = 0
    by_mod = {}
    for m in sorted(trees):
        by_mod.setdefault(m, [])
    for m, t in sorted(trees.items()):
        is_pkg = any(str(p).endswith("__init__.py") and mod_name(root, p) == m for p in files)
        names = imports(m, t, is_pkg)
        block = []
        for n in t.body:
            if not isinstance(n, ast.ClassDef):
                continue
            q = f"{m}.{n.name}"
            n_classes += 1
            fields, methods, assoc = {}, [], set()
            for s in n.body:
                if isinstance(s, (ast.Assign, ast.AnnAssign)):
                    for tg in (s.targets if isinstance(s, ast.Assign) else [s.target]):
                        if isinstance(tg, ast.Name):
                            fields.setdefault(tg.id, "{static} ")
                elif isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    methods.append(f"  {vis(s.name)} {stereo(s)}{s.name}({arg_str(s.args)})"
                                   + (f" : {ast.unparse(s.returns)}" if s.returns else ""))
                    for x in ast.walk(s):
                        if isinstance(x, ast.Assign):
                            for tg in x.targets:
                                if (isinstance(tg, ast.Attribute) and isinstance(tg.value, ast.Name)
                                        and tg.value.id == "self"):
                                    fields.setdefault(tg.attr, "")
                                    if isinstance(x.value, ast.Call):
                                        c = resolve(x.value.func, names)
                                        if c and c != q:
                                            assoc.add((c, tg.attr))
            block.append(f'  class "{n.name}" as {q} {{')
            block += [f"  {vis(f)} {fields[f]}{f}" for f in sorted(fields)]
            block += methods
            block.append("  }")
            n_members += len(fields) + len(methods)
            for b in n.bases:
                c = resolve(b, names)
                if c:
                    edges.add(f"{q} --|> {c}")
            for c, attr in sorted(assoc):
                edges.add(f"{q} --> {c} : {attr}")
            linked = {c for c, _ in assoc} | {resolve(b, names) for b in n.bases}
            for c in sorted(uses(n.body, names, q) - linked):
                edges.add(f"{q} ..> {c}")
        funcs = [s for s in t.body if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef))]
        if funcs:
            mq = f"{m}.__module__"
            block.append(f'  class "{m.rsplit(".", 1)[-1]} (module functions)" as {mq} <<module>> {{')
            block += [f"  {vis(f.name)} {f.name}({arg_str(f.args)})" for f in funcs]
            block.append("  }")
            n_members += len(funcs)
            for c in sorted(uses(funcs, names, None)):
                edges.add(f"{mq} ..> {c}")
        if block:
            lines.append(f"package {m} {{")
            lines += block
            lines.append("}")
    lines += sorted(edges)
    lines.append("@enduml")
    text = "\n".join(lines) + "\n"
    stats = {"files": len(files), "classes": n_classes, "members": n_members, "edges": len(edges),
             "lines": len(lines), "chars": len(text), "approx_tokens": len(text) // 4}
    return text, stats


if __name__ == "__main__":
    text, stats = build(Path(sys.argv[1]), sys.argv[2].split(","))
    Path(sys.argv[3]).write_text(text, encoding="utf-8", newline="\n")
    print(json.dumps(stats))
